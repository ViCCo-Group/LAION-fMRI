def test_anatomical_t2w_full_res(synthetic_data_dir):
    """T2w volume resolves at full resolution."""
    path = anatomical_file_path(
        synthetic_data_dir, "sub-01", suffix="T2w",
    )
    assert path.is_file()
    assert path.name.endswith("_space-T1w_T2w.nii.gz")


def test_anatomical_brain_mask_full_res(synthetic_data_dir):
    """Brain mask at full resolution uses ``desc-brain``."""
    path = anatomical_file_path(
        synthetic_data_dir, "sub-01",
        suffix="mask", desc="brain",
    )
    assert path.is_file()
    assert path.name == (
        "sub-01_ses-PrismaAnat_space-T1w_desc-brain_mask.nii.gz"
    )


def test_anatomical_brain_mask_res_1pt8(synthetic_data_dir):
    """Brain mask at ``res-1pt8`` is what aligns with the functional grid."""
    path = anatomical_file_path(
        synthetic_data_dir, "sub-01",
        suffix="mask", desc="brain", res="1pt8",
    )
    assert path.is_file()
    assert path.name == (
        "sub-01_ses-PrismaAnat_space-T1w"
        "_res-1pt8_desc-brain_mask.nii.gz"
    )


def test_anatomical_file_path_rejects_unknown_suffix(synthetic_data_dir):
    """Unknown ``suffix`` raises ``ValueError``."""
    with pytest.raises(ValueError, match="suffix"):
        anatomical_file_path(
            synthetic_data_dir, "sub-01", suffix="DWI",
        )


def test_anatomical_t1w_res_1pt5(synthetic_data_dir):
    """T1w at ``res-1pt5`` sits on the pRF / localizer grid."""
    path = anatomical_file_path(
        synthetic_data_dir, "sub-01", suffix="T1w", res="1pt5",
    )
    assert path.is_file()
    assert path.name == (
        "sub-01_ses-PrismaAnat_space-T1w_res-1pt5_T1w.nii.gz"
    )


def test_anatomical_tissue_mask_paths(synthetic_data_dir):
    """Every tissue label resolves on every grid, ``res`` before ``label``."""
    for res in ANATOMICAL_RESOLUTIONS:
        res_token = f"_res-{res}" if res else ""
        for label in TISSUE_LABELS:
            path = anatomical_file_path(
                synthetic_data_dir, "sub-01",
                suffix="mask", res=res, label=label,
            )
            assert path.is_file()
            assert path.name == (
                f"sub-01_ses-PrismaAnat_space-T1w{res_token}"
                f"_label-{label}_mask.nii.gz"
            )


def test_anatomical_file_path_rejects_unknown_label(synthetic_data_dir):
    """A label outside ``TISSUE_LABELS`` raises ``ValueError``."""
    with pytest.raises(ValueError, match="label must be one of"):
        anatomical_file_path(
            synthetic_data_dir, "sub-01", suffix="mask", label="GM",
        )


def test_anatomical_file_path_rejects_unknown_res(synthetic_data_dir):
    """A grid outside ``ANATOMICAL_RESOLUTIONS`` raises ``ValueError``."""
    with pytest.raises(ValueError, match="res must be one of"):
        anatomical_file_path(
            synthetic_data_dir, "sub-01", suffix="T1w", res="2pt0",
        )


@pytest.mark.parametrize(
    "desc, label", [(None, None), ("brain", "CGM"), ("other", None)],
)
def test_anatomical_mask_needs_exactly_one_of_desc_label(
    synthetic_data_dir, desc, label,
):
    """A mask takes ``desc="brain"`` or a label, never both or neither."""
    with pytest.raises(ValueError, match="exactly one"):
        anatomical_file_path(
            synthetic_data_dir, "sub-01",
            suffix="mask", desc=desc, label=label,
        )


def test_anatomical_label_only_for_masks(synthetic_data_dir):
    """``label`` on a T1w raises ``ValueError``."""
    with pytest.raises(ValueError, match="masks only"):
        anatomical_file_path(
            synthetic_data_dir, "sub-01", suffix="T1w", label="CGM",
        )
